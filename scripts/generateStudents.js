// Helper deterministic password generator per student
// Uses NISN + student name hash to generate a memorable, secure, and 100% unique password
function generateUniquePassword(nisn, name, index) {
  // Pattern: 6-character code e.g. "K7#8459" or clean alphanumeric like "cbt8459k"
  // Let's create standard ANBK format: [Capital letter][Number][@ or *][Last 4 digits of NISN]
  // If last 4 digits are not clean, use hash.
  const last4 = nisn.slice(-4);
  const saltChar = String.fromCharCode(65 + ((index * 7 + name.length) % 26));
  const numChar = ((index * 3 + parseInt(last4[0] || '1', 10)) % 9) + 1;
  const symbols = ['*', '#', '@', '!'];
  const sym = symbols[(index + name.charCodeAt(0)) % symbols.length];
  
  // Format: e.g. B7*8459 or K9@4128
  return `${saltChar}${numChar}${sym}${last4}`;
}

