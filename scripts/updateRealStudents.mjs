const usedOldIndices = new Set();

// Pass 1: Match manual aliases & exact same-class exact-name matches (handles NAFISHA VIII-2!)
for (const p of parsed) {
  const pNorm = norm(p.name);
  if (MANUAL_ALIAS_NISN[pNorm]) {
    const idx = oldList.findIndex((o, j) => !usedOldIndices.has(j) && o.nisn === MANUAL_ALIAS_NISN[pNorm]);
    if (idx !== -1) {
      usedOldIndices.add(idx);
      p.matchedOld = oldList[idx];
      continue;
    }
  }
  const exactSameClassIdx = oldList.findIndex(
    (o, j) => !usedOldIndices.has(j) && o.kelas === p.kelas && (norm(o.name) === pNorm || compact(o.name) === compact(p.name))
  );
  if (exactSameClassIdx !== -1) {
    usedOldIndices.add(exactSameClassIdx);
    p.matchedOld = oldList[exactSameClassIdx];
  }
}

// Pass 2: Cross-class exact norm match
for (const p of parsed) {
  if (p.matchedOld) continue;
  const pNorm = norm(p.name);
  const pComp = compact(p.name);
  const idx = oldList.findIndex(
    (o, j) => !usedOldIndices.has(j) && (norm(o.name) === pNorm || compact(o.name) === pComp)
  );
  if (idx !== -1) {
    usedOldIndices.add(idx);
    p.matchedOld = oldList[idx];
  }
}

// Pass 3: Fuzzy match remaining
for (const p of parsed) {
  if (p.matchedOld) continue;
  const pNorm = norm(p.name);
  const pComp = compact(p.name);
  const pTokens = pNorm.split(' ').filter(t => t.length > 1);
  let bestScore = Infinity;
  let candidateIdx = -1;

  for (let j = 0; j < oldList.length; j++) {
    if (usedOldIndices.has(j)) continue;
    const oNorm = norm(oldList[j].name);
    const oComp = compact(oldList[j].name);
    const dist = levenshtein(pComp, oComp);
    const ratio = dist / Math.max(pComp.length, oComp.length);
    const oTokens = oNorm.split(' ').filter(t => t.length > 1);
    const firstMatch = pTokens[0] === oTokens[0];
    const lastMatch = pTokens[pTokens.length - 1] === oTokens[oTokens.length - 1];

    if (ratio <= 0.25 && (firstMatch || lastMatch)) {
      if (dist < bestScore) {
        bestScore = dist;
        candidateIdx = j;
      }
    } else if (firstMatch && lastMatch && pTokens.length >= 2 && oTokens.length >= 2) {
      const pJoined = pTokens.join(' ');
      const oJoined = oTokens.join(' ');
      const d2 = levenshtein(pJoined, oJoined);
      if (d2 <= 12 && d2 < bestScore) {
        bestScore = d2;
        candidateIdx = j;
      }
    }
  }
  if (candidateIdx !== -1) {
    usedOldIndices.add(candidateIdx);
    p.matchedOld = oldList[candidateIdx];
  }
}

function generateUniquePassword(seedStr, name, index) {
  const last4 = seedStr.slice(-4).padStart(4, '0');
  const saltChar = String.fromCharCode(65 + ((index * 7 + name.length) % 26));
  const numChar = ((index * 3 + parseInt(last4[0] || '1', 10)) % 9) + 1;
  const symbols = ['*', '#', '@', '!'];
  const sym = symbols[(index + name.charCodeAt(0)) % symbols.length];
  return `${saltChar}${numChar}${sym}${last4}`;
}

function makeProvisionalUsername(kelas, no) {
  const [grade, rombel] = kelas.split('-');
  const gNum = grade === 'VII' ? '07' : grade === 'VIII' ? '08' : '09';
  return `26${gNum}${String(rombel).padStart(2, '0')}${String(no).padStart(3, '0')}`;
}

